def resample_rate(xs, src, dst):
    if src == dst:
        return xs
    step = src / dst
    out, t = [], 0.0
    while t < len(xs) - 1:
        i = int(t)
        f = t - i
        out.append(xs[i] * (1 - f) + xs[i + 1] * f)
        t += step
    return out


