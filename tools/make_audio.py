#!/usr/bin/env python3
"""Synthesizes every Outtap sound from scratch (no samples, no third-party audio).

Run: python3 tools/make_audio.py [--music]   (needs ffmpeg with libvorbis for the music loops)
Writes assets/audio/*.wav (effects) and, with --music, assets/audio/music_calm.ogg (menus),
assets/audio/music_tense.ogg (normal stages) and assets/audio/music_hard.ogg (HARD stages): seamless
loops built in a circular buffer.
The output is original work generated by this script and can be shipped commercially.
"""
from pathlib import Path
import math
import random
import struct
import subprocess
import wave

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets/audio"
RATE = 44100
TAU = math.tau


def write_wav(name, samples, rate=RATE):
    peak = max(1e-9, max(abs(s) for s in samples))
    gain = min(1.0, 0.89 / peak)  # normalize but never clip
    frames = b"".join(struct.pack("<h", int(max(-1.0, min(1.0, s * gain)) * 32767)) for s in samples)
    with wave.open(str(OUT / name), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(frames)


def env(t, attack, decay):
    if t < attack:
        return t / attack
    return math.exp(-(t - attack) / decay)


def tone(duration, f0, f1=None, attack=0.004, decay=0.08, harmonics=((1, 1.0),), curve=1.0):
    n = int(duration * RATE)
    out, phase = [], 0.0
    f1 = f0 if f1 is None else f1
    for i in range(n):
        t = i / RATE
        k = (t / duration) ** curve
        f = f0 + (f1 - f0) * k
        phase += TAU * f / RATE
        v = sum(a * math.sin(phase * h) for h, a in harmonics)
        out.append(v * env(t, attack, decay))
    return out


def noise(duration, decay, color=0.6, seed=1, attack=0.002):
    rng = random.Random(seed)
    n = int(duration * RATE)
    out, last = [], 0.0
    for i in range(n):
        t = i / RATE
        last = last * color + rng.uniform(-1, 1) * (1 - color)
        out.append(last * env(t, attack, decay))
    return out


def mix(*tracks, gains=None):
    length = max(len(t) for t in tracks)
    gains = gains or [1.0] * len(tracks)
    out = [0.0] * length
    for track, g in zip(tracks, gains):
        for i, s in enumerate(track):
            out[i] += s * g
    return out


def delay(track, seconds):
    return [0.0] * int(seconds * RATE) + track


def fade_out(track, seconds=0.01):
    n = int(seconds * RATE)
    for i in range(min(n, len(track))):
        track[-1 - i] *= i / n
    return track


def note(name):
    names = {"C": -9, "D": -7, "E": -5, "F": -4, "G": -2, "A": 0, "B": 2}
    base = names[name[0]]
    octave = int(name[-1])
    sharp = 1 if "#" in name else 0
    return 440.0 * 2 ** ((base + sharp + (octave - 4) * 12) / 12)


def bell(freq, duration, decay=0.25, gain=1.0):
    return [s * gain for s in tone(duration, freq, attack=0.003, decay=decay,
                                   harmonics=((1, 1.0), (2, 0.35), (3, 0.12), (4.2, 0.06)))]


def lowpass(track, cutoff):
    """One-pole low-pass: keeps effects warm (little energy above a few kHz)."""
    a = math.exp(-TAU * cutoff / RATE)
    out, y = [], 0.0
    for x in track:
        y = (1 - a) * x + a * y
        out.append(y)
    return out


def marimba(freq, duration, decay=0.32, gain=1.0):
    """Soft mallet tone: fundamental with a quickly fading 4th partial (wood, not glass)."""
    n = int(duration * RATE)
    out = []
    for i in range(n):
        t = i / RATE
        att = min(1.0, t / 0.003)
        v = math.sin(TAU * freq * t) * math.exp(-t / decay) + 0.22 * math.sin(TAU * 3.98 * freq * t) * math.exp(-t / 0.035)
        out.append(gain * att * v)
    return out


def whoosh(duration, rise=0.4, seed=7, color_from=0.95, color_to=0.75):
    """Air movement: noise whose brightness rises then falls, with a smooth bell envelope."""
    rng = random.Random(seed)
    n = int(duration * RATE)
    out, last = [], 0.0
    for i in range(n):
        t = i / n
        color = color_from + (color_to - color_from) * math.sin(math.pi * min(1.0, t / max(rise, 1e-3)) * 0.5)
        last = last * color + rng.uniform(-1, 1) * (1 - color)
        env = math.sin(math.pi * t) ** 1.5
        out.append(last * env)
    return out


def high_shelf_soft(track, amount=0.35):
    """Adds a little air: mixes in the difference between the signal and its 3 kHz low-pass."""
    low = lowpass(track, 3000)
    return [x + amount * (x - l) for x, l in zip(track, low)]


def riser(duration, seed=21):
    """Filtered noise that brightens and swells: anticipation before a reveal."""
    rng = random.Random(seed)
    n = int(duration * RATE)
    out, last = [], 0.0
    for i in range(n):
        t = i / n
        color = 0.97 - 0.25 * t
        last = last * color + rng.uniform(-1, 1) * (1 - color)
        out.append(last * (t ** 1.6))
    return out


def effects():
    # Menu: a short, soft wooden tick shared by every interface button and toggle.
    write_wav("ui_click.wav", fade_out(lowpass(mix(marimba(note("G5"), 0.09, decay=0.022),
                                                   noise(0.02, 0.004, color=0.4, seed=11), gains=[0.6, 0.12]), 4200)))
    write_wav("tap.wav", fade_out(lowpass(mix(tone(0.045, 760, 540, attack=0.001, decay=0.012),
                                              noise(0.03, 0.006, color=0.5, seed=2), gains=[0.7, 0.2]), 3500)))
    # Arrow slide: a soft swoosh carrying a wooden pluck at C5 (the streak raises it in-game).
    slide = mix(lowpass(whoosh(0.2, seed=3), 3000), marimba(523.25, 0.24, decay=0.09), gains=[0.55, 0.6])
    write_wav("slide.wav", fade_out(slide, 0.02))
    slide_long = mix(lowpass(whoosh(0.34, rise=0.5, seed=4), 2800), marimba(523.25, 0.3, decay=0.11),
                     delay(marimba(783.99, 0.22, decay=0.07, gain=0.35), 0.06), gains=[0.6, 0.55, 1.0])
    write_wav("slide_long.wav", fade_out(slide_long, 0.03))
    # Short arrows: a quicker, slightly higher flick.
    slide_short = mix(lowpass(whoosh(0.13, rise=0.3, seed=8), 3200), marimba(587.33, 0.17, decay=0.06), gains=[0.5, 0.6])
    write_wav("slide_short.wav", fade_out(slide_short, 0.015))
    # Path unlocked: an airy two-note lift, quiet; it sits under the slide when an exit opens.
    write_wav("path.wav", fade_out(lowpass(mix(marimba(note("E6"), 0.22, decay=0.06, gain=0.55),
                                              delay(marimba(note("A6"), 0.28, decay=0.08, gain=0.45), 0.045)), 6500), 0.02))
    # Golden arrow: a bright coin-like double bell.
    gold = mix(bell(note("B6"), 0.45, decay=0.1, gain=0.6), delay(bell(note("E7"), 0.6, decay=0.18, gain=0.55), 0.065))
    write_wav("gold.wav", fade_out(lowpass(gold, 9000), 0.04))
    # HARD intro: a low soft boom, a rising swell and a gong-like A.
    boom = tone(0.9, 72, 46, attack=0.006, decay=0.32, harmonics=((1, 1.0), (2, 0.25)))
    gong = bell(note("A3"), 1.4, decay=0.6, gain=0.45)
    write_wav("hard_intro.wav", fade_out(lowpass(mix(boom, delay(lowpass(riser(0.7), 5000), 0.1), delay(gong, 0.78),
                                                     gains=[0.8, 0.3, 1.0]), 6000), 0.12))
    # HARD clear: bright major arpeggio over a warm chord, with a shimmer tail.
    arp_h = mix(*[delay(marimba(note(n), 0.9 - i * 0.08, decay=0.3), i * 0.065)
                  for i, n in enumerate(["A4", "C#5", "E5", "A5", "C#6", "E6"])])
    chord = mix(*[[0.16 * v * min(1.0, k / (RATE * 0.12)) for k, v in enumerate(tone(1.8, note(n), attack=0.08, decay=0.8,
                                                                                     harmonics=((1, 1), (2, 0.3))))]
                  for n in ["A3", "E4", "A4", "C#5"]])
    shimmer = delay(mix(bell(note("E7"), 0.9, decay=0.35, gain=0.25), delay(bell(note("A7"), 0.8, decay=0.3, gain=0.18), 0.09)), 0.42)
    write_wav("clear_hard.wav", fade_out(lowpass(mix(arp_h, delay(chord, 0.3), shimmer), 7000), 0.15))
    # League promotion: a short rising fanfare.
    fan = mix(*[delay(marimba(note(n), 0.7, decay=0.26), i * 0.09) for i, n in enumerate(["G5", "C6", "E6", "G6"])],
              delay(bell(note("C7"), 0.9, decay=0.35, gain=0.3), 0.36))
    write_wav("promote.wav", fade_out(lowpass(fan, 7000), 0.1))
    # Wow: a sparkling upward sweep landing on a bright chord.
    sweep = tone(0.36, note("C6"), note("C7"), attack=0.01, decay=0.5, harmonics=((1, 1.0), (2, 0.2)), curve=0.7)
    sweep = [v * min(1.0, i / (RATE * 0.25)) * 0.35 for i, v in enumerate(sweep)]
    hit = mix(*[bell(note(n), 0.9, decay=0.3, gain=0.4) for n in ["C6", "E6", "G6"]])
    write_wav("wow.wav", fade_out(lowpass(mix(sweep, delay(hit, 0.32), delay(bell(note("C7"), 0.7, decay=0.25, gain=0.25), 0.4)), 8000), 0.1))
    # Collision: a muted knock, clearly lower and duller than the slide.
    knock = mix(tone(0.12, 190, 120, attack=0.002, decay=0.035, harmonics=((1, 1.0), (2, 0.18))),
                lowpass(noise(0.04, 0.008, color=0.6, seed=5), 1800), gains=[0.8, 0.35])
    write_wav("bump.wav", fade_out(lowpass(knock, 2500)))
    write_wav("life.wav", fade_out(mix(marimba(note("E5"), 0.2, decay=0.08), delay(marimba(note("C5"), 0.3, decay=0.12), 0.1))))
    write_wav("combo.wav", fade_out(lowpass(mix(marimba(note("C6"), 0.3, decay=0.12), delay(marimba(note("G6"), 0.26, decay=0.1, gain=0.6), 0.05)), 5000)))
    arp = mix(*[delay(marimba(note(n), 0.8 - i * 0.1, decay=0.28), i * 0.075) for i, n in enumerate(["C5", "E5", "G5", "C6"])])
    pad = [0.18 * s * min(1.0, i / (RATE * 0.25)) for i, s in enumerate(tone(1.0, note("C4"), attack=0.2, decay=0.45, harmonics=((1, 1), (1.5, 0.5), (2, 0.4))))]
    write_wav("clear.wav", fade_out(lowpass(mix(arp, pad, delay(marimba(note("E6"), 0.6, decay=0.3, gain=0.3), 0.3)), 5000), 0.06))
    write_wav("clear_small.wav", fade_out(lowpass(mix(marimba(note("G5"), 0.5, decay=0.2), delay(marimba(note("C6"), 0.55, decay=0.25), 0.08)), 5000), 0.05))
    write_wav("fail.wav", fade_out(mix(*[delay(marimba(note(n), 0.5, decay=0.2), i * 0.14) for i, n in enumerate(["G4", "E4", "C4"])]), 0.05))
    write_wav("hint.wav", fade_out(lowpass(mix(marimba(note("A5"), 0.35, decay=0.14), delay(marimba(note("E6"), 0.4, decay=0.16), 0.09), gains=[0.6, 0.6]), 5000)))
    write_wav("unlock.wav", fade_out(lowpass(mix(marimba(note("G5"), 0.8, decay=0.3), marimba(note("D6"), 0.8, decay=0.3, gain=0.6),
                                                 delay(marimba(note("G6"), 0.6, decay=0.25, gain=0.4), 0.12)), 5000), 0.05))


def music(path_ogg, bars=16, bpm=84):
    """Calm loop: soft pads on a four-chord cycle with sparse pentatonic plucks. The buffer is
    circular so every tail wraps into the start and the loop point is seamless."""
    rate = 32000
    beat = 60.0 / bpm
    total = int(bars * 4 * beat * rate)
    buf = [0.0] * total
    chords = [["C3", "G3", "B3", "E4"], ["A2", "E3", "G3", "C4"], ["F2", "C3", "E3", "A3"], ["G2", "D3", "F3", "B3"]]

    def add(start, samples):
        for i, s in enumerate(samples):
            buf[(start + i) % total] += s

    for bar in range(bars):
        chord = chords[bar % 4]
        start = int(bar * 4 * beat * rate)
        length = int(4 * beat * rate)
        for v, name in enumerate(chord):
            f = note(name)
            phase = v * 1.3
            seg = []
            for i in range(length + int(rate * 0.6)):
                t = i / rate
                a = min(1.0, t / 0.9) * (1.0 if i < length else math.exp(-(i - length) / (rate * 0.25)))
                wob = 1 + 0.004 * math.sin(TAU * 0.3 * t + v)
                seg.append(0.05 * a * (math.sin(TAU * f * wob * t + phase) + 0.25 * math.sin(TAU * 2 * f * t + phase)))
            add(start, seg)
    rng = random.Random(84)
    scale = ["C5", "D5", "E5", "G5", "A5", "C6", "E5", "G5"]
    for step in range(bars * 8):
        if rng.random() < 0.38:
            f = note(rng.choice(scale))
            start = int(step * beat * 0.5 * rate)
            seg = [0.09 * math.exp(-(i / rate) / 0.35) * min(1.0, i / (rate * 0.004)) *
                   (math.sin(TAU * f * i / rate) + 0.2 * math.sin(TAU * 3 * f * i / rate))
                   for i in range(int(rate * 1.2))]
            add(start, seg)
    peak = max(abs(s) for s in buf)
    gain = 0.5 / peak
    tmp = OUT / "_music.wav"
    with wave.open(str(tmp), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(b"".join(struct.pack("<h", int(s * gain * 32767)) for s in buf))
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(tmp), "-c:a", "libvorbis", "-q:a", "3", str(path_ogg)], check=True)
    tmp.unlink()


def groove_loop(path_ogg, bpm, shift, intensity, seed, bars=32):
    """Stage loop: a catchy minor-key hook over a dance groove. Tension comes from the harmony
    (i - bVI - bVII - V, ending every phrase on the major V that pulls back to i), the pumping pad and
    the syncopated bass, not from a clock. 32 bars:
      intro 4   drums + bass + pad
      A     8   the hook (4-bar call and answer, played twice)
      B     8   the hook an octave up with a counter line, open hats
      break 4   drums drop to a pulse, the hook muffled, a riser into
      A'    8   everything, hook doubled
    `shift` transposes (semitones), `intensity` (0..1) adds drive. Circular buffer: seamless loop."""
    rate = 32000
    beat = 60.0 / bpm
    step = beat / 4.0 # one sixteenth
    bar_len = 4 * beat
    total = int(bars * bar_len * rate)
    buf = [0.0] * total
    rng = random.Random(seed)
    tr = 2 ** (shift / 12)

    def add(start, samples, gain=1.0):
        for i, s in enumerate(samples):
            buf[(start + i) % total] += s * gain

    def at(bar, sixteenth):
        return int((bar * 16 + sixteenth) * step * rate)

    def lead(f, length, bright):
        # Soft pulse lead: odd harmonics (rounded by `bright`), a little vibrato after the attack.
        out = []
        n = int(length * rate)
        rel = int(0.06 * rate)
        for i in range(n + rel):
            t = i / rate
            a = min(1.0, t / 0.006) * (0.75 + 0.25 * math.exp(-t / 0.12))
            if i >= n:
                a *= math.exp(-(i - n) / (rel * 0.35))
            vib = 1 + 0.004 * math.sin(TAU * 5.5 * t) * min(1.0, max(0.0, (t - 0.15) / 0.2))
            ph = TAU * f * vib * t
            out.append(a * (math.sin(ph) + bright * (0.3 * math.sin(3 * ph) + 0.16 * math.sin(5 * ph) + 0.08 * math.sin(7 * ph))
                            + 0.15 * math.sin(2 * ph)))
        return out

    def bass(f, length):
        out = []
        for i in range(int(length * rate)):
            t = i / rate
            e = min(1.0, t / 0.003) * math.exp(-t / 0.16)
            ph = TAU * f * t
            out.append(e * (math.sin(ph) + 0.45 * math.sin(2 * ph) + 0.2 * math.sin(3 * ph) * math.exp(-t / 0.05)))
        return out

    kick = [math.sin(TAU * (48 * (i / rate) + 80 * 0.028 * (1 - math.exp(-(i / rate) / 0.028)))) * math.exp(-(i / rate) / 0.14)
            for i in range(int(0.4 * rate))]
    clap = [x * 1.2 for x in resample_rate(lowpass(noise(0.2, 0.06, color=0.25, seed=seed + 1), 5000), RATE, rate)]
    hat = resample_rate(lowpass(noise(0.035, 0.01, color=0.05, seed=seed + 2), 8000), RATE, rate)
    open_hat = resample_rate(lowpass(noise(0.18, 0.06, color=0.05, seed=seed + 3), 7500), RATE, rate)

    # Harmony: one chord per bar, A minor: Am - F - G - E.
    chords = [["A2", "C4", "E4", "A4"], ["F2", "C4", "F4", "A4"], ["G2", "D4", "G4", "B4"], ["E2", "B3", "E4", "G#4"]]
    # The hook: eighth-note slots per bar ("-" rest, "~" hold the previous note).
    hook = [["E5", "-", "E5", "A5", "~", "G5", "E5", "-"],
            ["F5", "~", "E5", "C5", "~", "D5", "~", "-"],
            ["D5", "-", "D5", "G5", "~", "F5", "D5", "-"],
            ["E5", "~", "B4", "~", "G#4", "~", "B4", "-"]]
    answer_end = ["E5", "~", "~", "-", "G#5", "~", "B5", "-"] # second pass: climbs instead of settling
    counter = [["C5", "~", "~", "~", "B4", "~", "A4", "~"], ["A4", "~", "~", "~", "G4", "~", "F4", "~"],
               ["B4", "~", "~", "~", "D5", "~", "B4", "~"], ["G#4", "~", "~", "~", "B4", "~", "E5", "~"]]

    def play_line(bar, slots, octave, gain, bright, echo=True):
        k = 0
        while k < 8:
            name = slots[k]
            if name in ("-", "~"):
                k += 1
                continue
            hold = 1
            while k + hold < 8 and slots[k + hold] == "~":
                hold += 1
            f = note(name) * tr * octave
            seg = lead(f, hold * 2 * step * 0.92, bright)
            s0 = at(bar, k * 2)
            add(s0, seg, gain)
            if echo: # dotted-eighth echo, panned in time only (mono)
                add(s0 + int(3 * step * rate), seg, gain * 0.28)
            k += hold

    for bar in range(bars):
        part = "intro" if bar < 4 else ("A" if bar < 12 else ("B" if bar < 20 else ("break" if bar < 24 else "A2")))
        chord = chords[bar % 4]
        root = note(chord[0]) * tr
        full = part in ("A", "B", "A2")
        # Pad: the chord, pumping (ducked on every beat like a sidechained synth).
        for name in chord[1:]:
            f = note(name) * tr
            seg = []
            n = int(bar_len * rate)
            for i in range(n):
                t = i / rate
                pump = min(1.0, ((t % beat) / (beat * 0.45)) ** 1.5)
                ph = TAU * f * t
                seg.append(pump * (math.sin(ph) + 0.25 * math.sin(2 * ph + 0.5)))
            add(at(bar, 0), seg, (0.022 if part != "break" else 0.03))
        # Bass: syncopated eighths with octave jumps; sixteenth pushes when intense.
        if part != "break":
            pattern = [(0, 1), (3, 1), (4, 2), (6, 1), (8, 1), (10, 2), (11, 1), (14, 1.5)]
            for sixteenth, mult in pattern:
                f = root * (2 if mult == 2 else (1.5 if mult == 1.5 else 1))
                add(at(bar, sixteenth), bass(f, step * 2.2), 0.2)
            if intensity > 0.5:
                for sixteenth in (13, 15):
                    add(at(bar, sixteenth), bass(root * 2, step * 1.2), 0.08)
        # Drums.
        if part == "break":
            for b in range(4):
                add(at(bar, b * 4), kick, 0.18 if bar < 22 else 0.3)
            if bar >= 22: # snare roll into the drop
                for k in range(0, 16, 2 if bar == 22 else 1):
                    add(at(bar, k), clap, 0.05 + 0.1 * (k / 16) * (bar - 21))
        else:
            for sixteenth in (0, 6, 8) + ((14,) if intensity > 0.5 or part == "A2" else ()):
                add(at(bar, sixteenth), kick, 0.42)
            if full or bar >= 2:
                for sixteenth in (4, 12):
                    add(at(bar, sixteenth), clap, 0.16)
            for sixteenth in range(16):
                if sixteenth % 4 == 2:
                    add(at(bar, sixteenth), open_hat if part in ("B", "A2") else hat, 0.06)
                elif sixteenth % 2 == 1 or intensity > 0.5:
                    add(at(bar, sixteenth), hat, 0.025 + 0.01 * rng.random())
        # Melody.
        slots = hook[bar % 4]
        second = (bar // 4) % 2 == 1
        if bar % 4 == 3 and second:
            slots = answer_end
        if part == "A":
            play_line(bar, slots, 1, 0.09, 0.8)
        elif part == "B":
            play_line(bar, slots, 2, 0.06, 0.6)
            play_line(bar, counter[bar % 4], 1, 0.05, 0.5, echo=False)
        elif part == "break":
            play_line(bar, hook[bar % 4], 1, 0.05, 0.15)
        elif part == "A2":
            play_line(bar, slots, 1, 0.08, 0.8)
            play_line(bar, slots, 2, 0.035, 0.4, echo=False)
            play_line(bar, counter[bar % 4], 0.5, 0.04, 0.4, echo=False)
    # Riser over the last two break bars into the drop.
    rise, last = [], 0.0
    n = int(2 * bar_len * rate)
    for i in range(n):
        k = i / n
        color = 0.97 - 0.55 * k
        last = last * color + rng.uniform(-1, 1) * (1 - color)
        rise.append(last * k ** 2 * 3.0)
    add(at(22, 0), rise, 0.04)
    # Loudness, not peak: body at about -19 dBFS RMS, transients rounded by a soft limiter.
    rms_now = math.sqrt(sum(x * x for x in buf) / len(buf))
    gain = 10 ** (-19 / 20) / max(1e-9, rms_now)
    buf = [0.85 * math.tanh(x * gain / 0.85) for x in buf]
    tmp = OUT / ("_" + Path(path_ogg).stem + ".wav")
    with wave.open(str(tmp), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(b"".join(struct.pack("<h", int(s * 32767)) for s in buf))
